export function loadStrategyProgress(): string[] {
  try {
    const raw = localStorage.getItem(STRATEGY_STORAGE_KEY);
    const parsed = raw ? (JSON.parse(raw) as { done?: string[] }) : {};
    return Array.isArray(parsed.done) ? parsed.done : [];
  } catch {
    return [];
  }
}

export function saveStrategyProgress(done: string[]): void {
  try {
    localStorage.setItem(STRATEGY_STORAGE_KEY, JSON.stringify({ done }));
  } catch {
    // storage blocked
  }
}

/** Markdown-версия стратегии для переноса в репозиторий и обсуждения с командой. */
export function strategyToMarkdown(): string {
  const lines: string[] = [];
  lines.push("# CityDrivingTraining — стратегия (ревизия)");
  lines.push("");
  lines.push("## Принципы");
  for (const p of PRINCIPLES) {
    lines.push(`- **${p.title}** — ${p.text} _${p.why}_`);
  }
  lines.push("");
  lines.push("## Фазы");
  for (const ph of STRATEGY_PHASES) {
    const mark = ph.status === "done" ? "✅" : ph.status === "active" ? "🟡" : "⬜";
    lines.push(`### ${mark} Этап ${ph.num}. ${ph.title} (${ph.period})`);
    lines.push(ph.goal);
    if (ph.done.length) {
      lines.push("Сделано:");
      for (const d of ph.done) lines.push(`- ${d}`);
    }
    if (ph.remaining.length) {
      lines.push("Осталось:");
      for (const r of ph.remaining) lines.push(`- ${r}`);
    }
    lines.push(`Метрика: ${ph.metric}`);
    lines.push("");
  }
  lines.push("## Приоритеты");
  for (const b of PRIORITIES) {
    lines.push(`### ${b.title}`);
    for (const item of b.items) lines.push(`- ${item}`);
    lines.push("");
  }
  lines.push("## Журнал решений");
  for (const d of DECISIONS) {
    lines.push(`- **${d.date} · ${d.title}** — ${d.decision} _${d.reason}_`);
  }
  lines.push("");
  lines.push("## Следующие действия");
  for (const a of NEXT_ACTIONS) lines.push(`- [ ] ${a.text} — ${a.hint}`);
  lines.push("");
  lines.push("---");
  lines.push("Учебная симуляция. Не заменяет практический экзамен в ГИБДД.");
  return lines.join("\n");
}
